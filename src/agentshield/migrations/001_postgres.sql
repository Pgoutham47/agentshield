CREATE TABLE IF NOT EXISTS schema_versions (version INTEGER PRIMARY KEY);
CREATE TABLE IF NOT EXISTS tasks (
 id TEXT PRIMARY KEY, tenant TEXT NOT NULL, idem TEXT NOT NULL,
 contract TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'active',
 calls INTEGER NOT NULL DEFAULT 0, bytes BIGINT NOT NULL DEFAULT 0,
 active INTEGER NOT NULL DEFAULT 0, UNIQUE(tenant,idem),
 rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
CREATE TABLE IF NOT EXISTS decisions (
 id TEXT PRIMARY KEY, task_id TEXT NOT NULL REFERENCES tasks(id),
 action_id TEXT NOT NULL, idem TEXT NOT NULL, action TEXT NOT NULL,
 response TEXT NOT NULL, state TEXT NOT NULL,
 UNIQUE(task_id,action_id), UNIQUE(task_id,idem),
 rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
CREATE TABLE IF NOT EXISTS grants (
 id TEXT PRIMARY KEY, task_id TEXT NOT NULL REFERENCES tasks(id),
 action TEXT NOT NULL, response TEXT NOT NULL, state TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS approvals (
 id TEXT PRIMARY KEY, decision_id TEXT NOT NULL REFERENCES decisions(id),
 task_id TEXT NOT NULL REFERENCES tasks(id), status TEXT NOT NULL, resolution TEXT,
 rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
CREATE TABLE IF NOT EXISTS executions (
 id TEXT PRIMARY KEY, decision_id TEXT UNIQUE NOT NULL,
 task_id TEXT NOT NULL REFERENCES tasks(id), state TEXT NOT NULL, result TEXT,
 rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
CREATE TABLE IF NOT EXISTS repos (task_id TEXT PRIMARY KEY REFERENCES tasks(id), state TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS github_inflight (
 repository TEXT PRIMARY KEY, execution_id TEXT NOT NULL REFERENCES executions(id));
CREATE TABLE IF NOT EXISTS events (seq BIGINT PRIMARY KEY, event TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS tasks_tenant_order ON tasks(tenant,rowid);
CREATE INDEX IF NOT EXISTS decisions_task_order ON decisions(task_id,rowid);
CREATE INDEX IF NOT EXISTS executions_task ON executions(task_id);
CREATE INDEX IF NOT EXISTS events_tenant_order ON events ((event::jsonb ->> 'tenant'),seq);
CREATE OR REPLACE FUNCTION reject_audit_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'append-only audit'; END;
$$;
DROP TRIGGER IF EXISTS events_immutable ON events;
CREATE TRIGGER events_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON events
 FOR EACH STATEMENT EXECUTE FUNCTION reject_audit_mutation();
INSERT INTO schema_versions(version) VALUES (1) ON CONFLICT DO NOTHING;
